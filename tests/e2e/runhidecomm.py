# Owner decision 6 Nov: the driver app does not show the commission anywhere (request card, end of ride,
# earnings, wallet card, wallet history, help). It is still taken from the wallet and stored on the booking;
# the driver agreement still states it. Wallet card shows only the minimum balance to go online.
import asyncio,re
from playwright.async_api import async_playwright
B='http://localhost:8765/tests/e2e/out/'
res=[]
def check(n,c,i=''):res.append(bool(c));print(('PASS ' if c else 'FAIL ')+n,i)
BAD=re.compile(r'commission|கமிஷன்|கழி|You get|உங்களுக்கு ₹|நிகர',re.I)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch();ctx=await b.new_context(viewport={'width':1900,'height':880},geolocation={'latitude':12.955,'longitude':79.139},permissions=['geolocation'])
        pg=await ctx.new_page();errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.goto(B+'harness_x.html');await pg.wait_for_timeout(2500)
        await pg.evaluate("MOCK.store.set('config/app',{comm:10,minbal:100})")
        C=pg.frame_locator('#c');D=pg.frame_locator('#d');cf=pg.frame(url=B+'c2.html');df=pg.frame(url=B+'d2.html')
        txt=lambda:df.evaluate("document.body.innerText")
        await D.locator('#ph').fill('9999900002');await D.locator('#go').click();await pg.wait_for_timeout(300)
        for i,d in enumerate('123456'):await D.locator(f'#o{i}').fill(d)
        await D.locator('#go').click();await pg.wait_for_timeout(1200);await D.locator('#ons').click();await pg.wait_for_timeout(1500)
        w0=await pg.evaluate("MOCK.store.get('drivers/+919999900002').wallet")
        await C.locator('#go').click();await pg.wait_for_timeout(300)
        await C.locator('#ph').fill('9999900001');await C.locator('#go').click();await pg.wait_for_timeout(500)
        for i,d in enumerate('123456'):await C.locator(f'#o{i}').fill(d)
        await pg.wait_for_timeout(800);await C.locator('#nm').fill('Priya');await C.locator('#go').click();await pg.wait_for_timeout(2000)
        await cf.evaluate("S.dest='cmc';S.veh='sedan';S.pay='cash';fareScreen()");await pg.wait_for_timeout(1200)
        await C.locator('#bookb').click();await pg.wait_for_timeout(3000);bid=await cf.evaluate("R.id")
        t=await txt();check('request card: no commission / "you get"',not BAD.search(t),BAD.findall(t))
        await D.locator('#acc').click();await pg.wait_for_timeout(2000)
        now=await pg.evaluate("Date.now()")
        await pg.evaluate(f"MOCK.fs.updateDoc({{path:'bookings/{bid}'}},{{arrivedAt:{{toMillis(){{return {now-2*60e3}}}}},startedAt:{{toMillis(){{return {now-60e3}}}}},status:'ontrip'}})");await pg.wait_for_timeout(1500)
        await df.evaluate("collect()");await pg.wait_for_timeout(600)
        await D.locator('#got').click();await pg.wait_for_timeout(2000)
        bk=await pg.evaluate(f"MOCK.dump()['bookings/{bid}']")
        check('ride closed',bk['status']=='done',bk['status'])
        t=await txt();check('end of ride: no commission line',not BAD.search(t),BAD.findall(t))
        amt=await df.evaluate("(document.querySelector('.earncard b')||{}).textContent||''")
        check('end of ride shows the ride amount (bill + tip)',amt.replace('₹','').replace(',','').strip()==str(int(bk['fareFinal'])+int(bk.get('tip') or 0)),(amt,bk['fareFinal']))
        w1=await pg.evaluate("MOCK.store.get('drivers/+919999900002').wallet")
        check('commission still taken from the wallet and stored on the ride',bk.get('comm',0)>0 and w0-w1==bk['comm'],(w0,w1,bk.get('comm')))
        await df.evaluate("document.querySelectorAll('.modal').forEach(m=>m.remove());stopJob();J=null;S.tab='earn';earnTab()");await pg.wait_for_timeout(1500)
        t=await txt();check('earnings: no commission',not BAD.search(t),BAD.findall(t))
        check('earnings total = bill + tip',str(int(bk['fareFinal'])+int(bk.get('tip') or 0)) in t.replace(',',''),'')
        await df.evaluate("S.tab='wallet';walletTab()");await pg.wait_for_timeout(1500)
        t=await txt();check('wallet: no commission line or history',not BAD.search(t),BAD.findall(t))
        check('wallet card says minimum ₹100 to go online',('குறைந்தது ₹100' in t) or ('at least ₹100' in t),'')
        faq=await df.evaluate("JSON.stringify(FAQD)")
        check('help: no commission question',not re.search(r'commission',faq,re.I))
        ag=open('../../core/driverchecks.js',encoding='utf-8').read()
        check('driver agreement still states the commission',"commission for each trip is taken from my wallet" in ag)
        check('no page errors',not errs,errs)
        await b.close()
asyncio.run(main())
print('RESULT','PASS' if all(res) else 'FAIL','%d/%d'%(sum(res),len(res)))
