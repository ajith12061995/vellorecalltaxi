# A final bill far above the booked fare: the driver app asks to double-check; the office rings "💰 High bill",
# shows it in the booking, and the owner marks it reviewed. A normal bill does neither.
import asyncio
from playwright.async_api import async_playwright
B='http://localhost:8765/tests/e2e/out/'
res=[]
def check(n,c,i=''):res.append(bool(c));print(('PASS ' if c else 'FAIL ')+n,i)
async def ride(pg,C,D,cf,df,toll):
    await cf.evaluate("S.dest='cmc';S.veh='sedan';S.pay='cash';fareScreen()");await pg.wait_for_timeout(1200)
    await C.locator('#bookb').click();await pg.wait_for_timeout(3000);bid=await cf.evaluate("R.id")
    await D.locator('#acc').click();await pg.wait_for_timeout(2000)
    now=await pg.evaluate("Date.now()")
    await pg.evaluate(f"MOCK.fs.updateDoc({{path:'bookings/{bid}'}},{{arrivedAt:{{toMillis(){{return {now-2*60e3}}}}},startedAt:{{toMillis(){{return {now-60e3}}}}},status:'ontrip'}})");await pg.wait_for_timeout(1500)
    await df.evaluate("collect()");await pg.wait_for_timeout(600)
    await D.locator('#adj').click();await pg.wait_for_timeout(400)
    await D.locator('#ttl').fill(str(toll));await D.locator('#ttl').dispatch_event('input');await pg.wait_for_timeout(200)
    await D.locator('#tok').click();await pg.wait_for_timeout(600)
    await D.locator('#got').click();await pg.wait_for_timeout(800)
    return bid
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch();ctx=await b.new_context(viewport={'width':1900,'height':880},geolocation={'latitude':12.955,'longitude':79.139},permissions=['geolocation'])
        pg=await ctx.new_page();errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.goto(B+'harness_x.html');await pg.wait_for_timeout(2500)
        await pg.evaluate("MOCK.store.set('config/app',{comm:10,minbal:100})")
        C=pg.frame_locator('#c');D=pg.frame_locator('#d');O=pg.frame_locator('#o')
        cf=pg.frame(url=B+'c2.html');df=pg.frame(url=B+'d2.html');of=pg.frame(url=B+'o2.html')
        await O.locator('#ph').fill('8220201462');await O.locator('#lgn').click();await pg.wait_for_timeout(300)
        await O.locator('#otp').fill('123456');await pg.wait_for_timeout(1500)
        await D.locator('#ph').fill('9999900002');await D.locator('#go').click();await pg.wait_for_timeout(300)
        for i,d in enumerate('123456'):await D.locator(f'#o{i}').fill(d)
        # auto sign-in when the 6th digit is in
        await pg.wait_for_timeout(1200);await D.locator('#ons').click();await pg.wait_for_timeout(1500)
        await C.locator('#go').click();await pg.wait_for_timeout(300)
        await C.locator('#ph').fill('9999900001');await C.locator('#go').click();await pg.wait_for_timeout(500)
        for i,d in enumerate('123456'):await C.locator(f'#o{i}').fill(d)
        await pg.wait_for_timeout(800);await C.locator('#nm').fill('Priya');await C.locator('#go').click();await pg.wait_for_timeout(2000)
        # 1) normal bill (small toll): no question, no alert
        bid1=await ride(pg,C,D,cf,df,20)
        check('normal bill: no double-check',not await df.evaluate("!!document.getElementById('bok')"))
        await pg.wait_for_timeout(1500)
        st1=(await pg.evaluate(f"MOCK.dump()['bookings/{bid1}']"))['status']
        check('normal bill closes the ride',st1=='done',st1)
        await df.evaluate("document.querySelectorAll('.modal').forEach(m=>m.remove());stopJob();J=null;home()");await pg.wait_for_timeout(600)
        await cf.evaluate("stopWatch();forgetRide();R=null;home()");await pg.wait_for_timeout(600)
        # 2) inflated bill (₹400 "toll")
        bid2=await ride(pg,C,D,cf,df,400)
        q=await df.evaluate("document.querySelector('.modal')?document.querySelector('.modal').innerText:''")
        check('driver asked to double-check a high bill',('அதிகமா' in q) or ('much higher' in q),q[:90])
        check('ride not closed before confirming',(await pg.evaluate(f"MOCK.dump()['bookings/{bid2}']"))['status']=='ontrip')
        await pg.screenshot(path='shots/bill_driver.png',clip={'x':400,'y':0,'width':400,'height':860})
        await D.locator('#bok').click();await pg.wait_for_timeout(1800)
        bk=await pg.evaluate(f"MOCK.dump()['bookings/{bid2}']")
        check('after "it is correct" the ride closes with the bill',bk['status']=='done' and bk.get('fareFinal',0)>bk['fare']*1.5,(bk['fare'],bk.get('fareFinal')))
        await of.evaluate("remap();ringCheck()");await pg.wait_for_timeout(500)
        bar=await of.evaluate("(document.getElementById('ringbar')||{}).innerText||''")
        check('office rings: 💰 High bill',('Bill அதிகம்' in bar) or ('High bill' in bar),bar[:120].replace('\n',' '))
        check('normal ride not in the alert',bar.count('💰')==1)
        await O.locator('#rgo').click();await pg.wait_for_timeout(900)
        sh=await of.evaluate("(document.querySelector('.modal')||{}).innerText||''")
        check('booking shows quote → bill (+%)',('Bill அதிகம்' in sh or 'High bill' in sh) and '%' in sh,[l for l in sh.split('\n') if '→' in l][:1])
        box=await pg.evaluate("(()=>{const r=document.getElementById('o').getBoundingClientRect();return [r.x,r.y,r.width,r.height]})()")
        await pg.screenshot(path='shots/bill_office.png',clip={'x':box[0],'y':box[1],'width':box[2],'height':box[3]})
        await O.locator('#bbok').click();await pg.wait_for_timeout(1200)
        bk=await pg.evaluate(f"MOCK.dump()['bookings/{bid2}']")
        await of.evaluate("remap();ringCheck()");await pg.wait_for_timeout(500)
        bar=await of.evaluate("(document.getElementById('ringbar')||{}).innerText||''")
        check('owner marks it reviewed; alert stops',bk.get('billOk') and bk['billOk'].get('by')=='+918220201462' and '💰' not in bar,(bk.get('billOk'),bar[:40]))
        check('no page errors',not errs,errs[:3])
        await b.close()
    print('RESULT','PASS' if all(res) else 'FAIL',f'{sum(res)}/{len(res)}')
asyncio.run(main())
