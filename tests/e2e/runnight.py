# Night charge: the owner turns it on in Office → Settings (hours + %); the customer app adds it to the quote
# for a pickup inside the hours (with a 🌙 note), saves it in the booking, the driver's final bill shows it on its
# own line with the same total, and the office phone-booking price adds it too. Outside the hours / switched off:
# the normal fare.
import asyncio, datetime
from playwright.async_api import async_playwright
B='http://localhost:8765/tests/e2e/out/'
res=[]
def check(n,c,i=''):res.append(bool(c));print(('PASS ' if c else 'FAIL ')+n,i)
ist=datetime.datetime.utcnow()+datetime.timedelta(hours=5,minutes=30)
hhmm=lambda d:d.strftime('%H:%M')
INSIDE=(hhmm(ist-datetime.timedelta(hours=1)),hhmm(ist+datetime.timedelta(hours=1)))
OUTSIDE=(hhmm(ist+datetime.timedelta(hours=2)),hhmm(ist+datetime.timedelta(hours=4)))
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch();ctx=await b.new_context(viewport={'width':1900,'height':880},geolocation={'latitude':12.955,'longitude':79.139},permissions=['geolocation'])
        pg=await ctx.new_page();errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.goto(B+'harness_x.html');await pg.wait_for_timeout(2500)
        await pg.evaluate("MOCK.store.set('config/app',{comm:10,minbal:100})")
        C=pg.frame_locator('#c');D=pg.frame_locator('#d');O=pg.frame_locator('#o')
        cf=pg.frame(url=B+'c2.html');df=pg.frame(url=B+'d2.html');of=pg.frame(url=B+'o2.html')
        await O.locator('#ph').fill('8220201462');await O.locator('#lgn').click();await pg.wait_for_timeout(300)
        await O.locator('#otp').fill('123456');await pg.wait_for_timeout(1500)
        await D.locator('#ph').fill('9999900002');await D.locator('#go').click();await pg.wait_for_timeout(300)
        for i,d in enumerate('123456'):await D.locator(f'#o{i}').fill(d)
        await D.locator('#go').click();await pg.wait_for_timeout(1200);await D.locator('#ons').click();await pg.wait_for_timeout(1500)
        await C.locator('#go').click();await pg.wait_for_timeout(300)
        await C.locator('#ph').fill('9999900001');await C.locator('#go').click();await pg.wait_for_timeout(500)
        for i,d in enumerate('123456'):await C.locator(f'#o{i}').fill(d)
        await pg.wait_for_timeout(800);await C.locator('#nm').fill('Priya');await C.locator('#go').click();await pg.wait_for_timeout(2000)
        async def quote():
            await cf.evaluate("S.dest='cmc';S.veh='sedan';S.pay='cash';S.when=null;fareScreen()");await pg.wait_for_timeout(900)
            return await cf.evaluate("[fare(VEH.find(v=>v.id==='sedan'),route(S.from,S.dest).km),fare0(VEH.find(v=>v.id==='sedan'),route(S.from,S.dest).km),!!document.getElementById('nightnote'),document.getElementById('bookb').textContent]")
        q0=await quote()
        check('before: normal fare, no night note',q0[0]==q0[1] and not q0[2],q0)
        # owner sets the night charge in Settings (hours around now)
        await of.evaluate("S.sec='set';show()");await pg.wait_for_timeout(800)
        check('settings show night switch, hours and % (defaults 22:00–05:00, 25%)',await of.evaluate("document.getElementById('ntf').value==='22:00'&&document.getElementById('ntt').value==='05:00'&&document.getElementById('ntp').value==='25'&&!document.getElementById('nton').checked"))
        await O.locator('#ntp').fill('0');await O.locator('#nton').check();await O.locator('#sv').click();await pg.wait_for_timeout(600)
        check('0 % with the switch on is refused',not (await pg.evaluate("(MOCK.store.get('config/app')||{}).night")))
        await O.locator('#ntp').fill('25');await O.locator('#ntf').fill(INSIDE[0]);await O.locator('#ntt').fill(INSIDE[1])
        await O.locator('#sv').click();await pg.wait_for_timeout(1500)
        nt=await pg.evaluate("(MOCK.store.get('config/app')||{}).night")
        check('saved to config/app.night',nt and nt['on'] and nt['pct']==25 and nt['from']==INSIDE[0],nt)
        q1=await quote()
        check('customer quote +25 % (rounded to ₹5) with 🌙 note',q1[0]==round(q0[1]*1.25/5)*5 and q1[2] and str(q1[0]) in q1[3],q1)
        await pg.screenshot(path='shots/night_quote.png',clip={'x':0,'y':0,'width':400,'height':860})
        check('scheduled outside the hours: normal fare',await cf.evaluate("(()=>{S.when=Date.now()+3*36e5;const v=VEH.find(v=>v.id==='sedan'),k=route(S.from,S.dest).km,r=fare(v,k)===fare0(v,k);S.when=null;return r})()"))
        await C.locator('#bookb').click();await pg.wait_for_timeout(3000);bid=await cf.evaluate("R.id")
        bk=await pg.evaluate(f"MOCK.dump()['bookings/{bid}']")
        check('booking saves the night fare and the night part',bk['fare']==q1[0] and bk['tariff'].get('night')==25 and bk['tariff'].get('nightAmt')==q1[0]-q1[1],(bk['fare'],bk['tariff']))
        await D.locator('#acc').click();await pg.wait_for_timeout(2000)
        now=await pg.evaluate("Date.now()")
        await pg.evaluate(f"MOCK.fs.updateDoc({{path:'bookings/{bid}'}},{{arrivedAt:{{toMillis(){{return {now-2*60e3}}}}},startedAt:{{toMillis(){{return {now-60e3}}}}},status:'ontrip'}})");await pg.wait_for_timeout(1500)
        await df.evaluate("collect()");await pg.wait_for_timeout(600)
        bill=await df.evaluate("document.body.innerText")
        check('driver bill shows the night line',('இரவு கட்டணம் +25%' in bill) or ('Night charge +25%' in bill))
        await pg.screenshot(path='shots/night_bill.png',clip={'x':400,'y':0,'width':400,'height':860})
        await D.locator('#got').click();await pg.wait_for_timeout(1800)
        bk=await pg.evaluate(f"MOCK.dump()['bookings/{bid}']")
        check('final bill total = booked night fare (no double charge)',bk['status']=='done' and bk.get('fareFinal')==q1[0],(bk.get('fareFinal'),q1[0]))
        # office phone booking price
        o=await of.evaluate("[fareO('sedan',5),fareO('sedan',5,Date.now())]")
        check('office phone booking: night price for now',o[1]==round(o[0]*1.25/5)*5,o)
        # outside the hours, then switched off
        await of.evaluate("S.sec='set';show()");await pg.wait_for_timeout(800)
        await O.locator('#ntf').fill(OUTSIDE[0]);await O.locator('#ntt').fill(OUTSIDE[1]);await O.locator('#sv').click();await pg.wait_for_timeout(1500)
        await cf.evaluate("document.querySelectorAll('.modal').forEach(m=>m.remove());try{stopWatch();forgetRide()}catch(e){};R=null;home()");await pg.wait_for_timeout(600)
        q2=await quote()
        check('outside the hours: normal fare',q2[0]==q2[1] and not q2[2],q2)
        await of.evaluate("S.sec='set';show()");await pg.wait_for_timeout(800)
        await O.locator('#ntf').fill(INSIDE[0]);await O.locator('#ntt').fill(INSIDE[1]);await O.locator('#nton').uncheck();await O.locator('#sv').click();await pg.wait_for_timeout(1500)
        q3=await quote()
        check('switched off: normal fare',q3[0]==q3[1] and not q3[2],q3)
        check('no page errors',not errs,errs[:3])
        await b.close()
    print('RESULT','PASS' if all(res) else 'FAIL',f'{sum(res)}/{len(res)}')
asyncio.run(main())
