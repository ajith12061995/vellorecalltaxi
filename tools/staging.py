#!/usr/bin/env python3
"""Builds the TEST copy of the apps at  staging/  →  https://velloretaxi.app/staging/
Every address containing "staging" uses the separate TEST Firebase project (firebase-config.js), so testing there
never touches real customers, drivers, trips or money. Run automatically by tools/bump.py on every release, so the
test copy is always the same code as the live one. Pages get noindex (not shown in Google) and a red TEST banner
(added by vct-cloud.js). Git stores identical files once, so the copy costs almost no space."""
import os, shutil, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, 'staging')
COPY = ['index.html', 'driver', 'office', 'join', 'privacy', 'core', 'vehicles', 'brand', 'manifest.webmanifest',
        'sw.js', 'fcm-sw.js', 'vct-cloud.js', 'firebase-config.js', 'maps-config.js', 'version.json',
        'icon-192.png', 'icon-512.png', 'icon-maskable-512.png', 'apple-touch-icon.png']
if os.path.isdir(out): shutil.rmtree(out)
os.makedirs(out)
for name in COPY:
    src = os.path.join(root, name)
    if not os.path.exists(src): continue
    dst = os.path.join(out, name)
    (shutil.copytree if os.path.isdir(src) else shutil.copy2)(src, dst)
n = 0
for d, _, fs in os.walk(out):
    for f in fs:
        if not f.endswith('.html'): continue
        p = os.path.join(d, f); s = open(p, encoding='utf-8').read()
        if 'name="robots"' not in s:
            s = re.sub(r'<head>', '<head><meta name="robots" content="noindex,nofollow">', s, count=1)
        open(p, 'w', encoding='utf-8').write(s); n += 1
open(os.path.join(out, 'README.txt'), 'w').write('Generated by tools/staging.py - do not edit here. TEST copy of the apps (separate Firebase project).\n')
print('staging copy:', n, 'pages')
